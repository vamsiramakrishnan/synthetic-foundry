# 6. Negative numbers follow the genome's `number_negatives` convention
# ---------------------------------------------------------------------------


def _docx_body_text(payload: bytes) -> str:
    document = python_docx.Document(io.BytesIO(payload))
    parts = [p.text for p in document.paragraphs]
    for table in document.tables:
        for row in table.rows:
            parts.extend(cell.text for cell in row.cells)
    return "\n".join(parts)


def _pptx_deck_text(payload: bytes) -> str:
    deck = python_pptx.Presentation(io.BytesIO(payload))
    parts: list[str] = []
    for slide in deck.slides:
        for shape in slide.shapes:
            if getattr(shape, "has_table", False):
                parts.extend(cell.text for row in shape.table.rows for cell in row.cells)
            elif getattr(shape, "has_text_frame", False) and shape.text_frame.text:
                parts.append(shape.text_frame.text)
    return "\n".join(parts)


@pytest.mark.parametrize("seed", list(range(20)))
def test_negatives_read_the_same_in_every_format(seed: int) -> None:
    """The genome must NOT change how a number is spelled.

    This test used to assert the opposite — that DOCX and PPTX each followed
    the genome's `number_negatives`. That was wrong, and `test_docx.py` caught
    it: a table read `-10,200` in Word and `(10,200)` in the Markdown rendering
    of the same IR. `render/values.py` exists so that cannot happen ("one
    function, so there is one answer"), and a per-renderer override
    reintroduces exactly the divergence it was written to eliminate — silently,
    because each format stays internally consistent.

    Varying the convention is still legitimate diversity. It just has to be a
    corpus-wide decision expressed once, through the IR's own `number_format`,
    so every renderer reaches the same answer through `format_value`.
    """
    ir = _ir(seed, negative=True)
    docx_body = _docx_body_text(docx_renderer.render(ir))
    pptx_body = _pptx_deck_text(pptx_renderer.render(ir))

    for figure in ("(4,200)", "(9,800)"):
        assert figure in docx_body, f"seed {seed}: {figure} missing from Word"
        assert figure in pptx_body, f"seed {seed}: {figure} missing from the deck"
    for wrong in ("-4,200", "-9,800"):
        assert wrong not in docx_body, f"seed {seed}: Word diverged to {wrong}"
        assert wrong not in pptx_body, f"seed {seed}: the deck diverged to {wrong}"


def test_number_negatives_convention_varies_across_the_sample() -> None:
    """A convention nobody in the sample ever picks the other way is not
    actually being read from the genome — this is the same
    "not-a-constant-in-disguise" check `test_docx.py`/`test_pptx.py` run for
    other invariants."""
    # Note this checks the *genome* samples both conventions, not that any
    # renderer honours one — no renderer does, deliberately, per the test above.
    # It stays because the field is real and will be consumed once the
    # convention is expressed through the IR's `number_format`, where every
    # format reads it and they cannot disagree.
    conventions = {genome(Rng(seed).derive("style")).number_negatives for seed in range(20)}
    assert conventions == {"parenthesised", "minus"}
