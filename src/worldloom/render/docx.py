"""The DOCX renderer.

Word is where enterprise narrative actually lives. A retrieval corpus made of
Markdown is a corpus of a shape no enterprise has — the memo a controller writes
is a ``.docx`` with a byline, headings, and a table pasted out of the workbook,
and a system that has only ever been tested on Markdown has not been tested on
the thing it will meet.

Same rule as every other format: this reads the IR and nothing else. The prose it
writes is the prose the narrative compiler already produced and the harness
already validated; the figures it writes come from the same resolved cells the
workbook computes. Nothing here can introduce a number, because nothing here is
given the chance to compute one.

Hidden sections are rendered, marked. Markdown includes them and so must this —
a "supporting facts" appendix present in one format and absent in the other would
be two documents of one artifact disagreeing about what the artifact contains,
which is the failure this project exists to prevent. Hidden means *not part of
the readable surface*, not *not written down*.
"""

