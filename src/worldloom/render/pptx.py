#: The palette `genome(rng, archetype="house")` reproduces exactly — the pptx
#: analogue of `docx.py`'s own `_HEADER_FILL`/`_SUBTOTAL_FILL` pair. Kept as
#: the fixed reference point the sampling space is built around and as the
#: source of `_HOUSE_GENOME` below; the renderer itself now reads every
#: colour off that document's own world-seeded genome instead.
_HEADER_FILL = "2F4858"
_ACCENT_FILL = "EDF2F4"
_NEGATIVE = "9B2226"
_INK = "1B1F22"
_MUTED = "6B747B"
_SUBTITLE_INK = "4A555C"
_WHITE = "FFFFFF"

#: No text on any slide goes below this. PowerPoint's own accessibility
#: checker starts flagging body copy under 18pt for a *projected* deck, but
#: nothing this renderer produces is meant to be read from the back of a room
#: — it is read on a screen, the same way the DOCX and Markdown twins of the
#: same artifact are. 12pt is the floor below which even screen reading starts
#: to strain, and it is deliberately not lower than the smallest text DOCX
#: itself ever uses (`docx.py`'s footnote and table text sit at 8-9pt, but
#: that is on an A4 page held close, which a slide viewed at arm's length is
#: not).
MIN_FONT_PT = 12


def _rgb(hexcode: str):  # type: ignore[no-untyped-def]
    from pptx.dml.color import RGBColor

    return RGBColor.from_string(hexcode)


def _pt(size: int):  # type: ignore[no-untyped-def]
    from pptx.util import Pt

    assert size >= MIN_FONT_PT, f"{size}pt would sit below the {MIN_FONT_PT}pt floor — see MIN_FONT_PT"
    return Pt(size)


