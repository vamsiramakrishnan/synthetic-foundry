"""The PPTX renderer.

A board deck is where the executive summary this project already emits
actually gets consumed — nobody hands a CFO a Markdown file. Per
``docs/artifact-compiler.md`` sections 9.1 and 14.A, this is the vertical
slice: one artifact type, the pipeline that document describes end to end, and
nothing wider.

::

    ArtifactIR -> PresentationPlan -> slide components -> geometry solve
    -> python-pptx -> OOXML normalisation -> structural validation

Same rule as every other renderer in this package: this reads the IR and
nothing else. The compiler (``worldloom.compiler``) turns the IR into a
validated sequence of component ids — the same deterministic, grammar-checked
composition any format in this repo could reach for — and this module's only
job is to spell that sequence as shapes. Nothing here computes a number,
resolves a fact, or decides which rows belong in a table; every value that
lands on a slide is either prose the narrative compiler already validated
(with ``{{fact:ID}}`` substituted the same way ``docx`` and ``markdown`` do)
or a cell that was already sitting in a resolved ``Table``.

``PresentationPlan``, ``SlidePlan`` and ``Box`` are renderer-local. Per
``docs/artifact-compiler.md`` section 2, a format plan is a rendering concern
— it is rebuilt from the IR every time a deck is wanted and is never
persisted, so it cannot drift from the artifact it describes the way a second
hand-kept structure could. None of the three belongs in ``models.py``.

Geometry is explicit ``Box(x, y, cx, cy)`` arithmetic against a handful of
module constants, not a constraint solver. Per section 14.E, CP-SAT and a
Cassowary solver are justified only once greedy layout fails a recorded
fixture — this renderer has one artifact type and at most a handful of shapes
per slide, and reaching for a solver here would be solving a problem that
does not exist yet.
"""

