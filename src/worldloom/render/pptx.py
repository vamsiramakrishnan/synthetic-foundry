def render(
    ir: ArtifactIR,
    facts: dict[str, CanonicalFact] | None = None,
    *,
    locale: Locale = DEFAULT_LOCALE,
    profile: PresentationProfile = DEFAULT_PRESENTATION,
) -> bytes:
    """Render one IR to PPTX bytes.

    Prose carries ``{{fact:ID}}`` references; *facts* resolves them at render
    time. Without it the references stay visible, which is the right failure —
    a deck that quietly drops a figure reads as finished and is not.

    *locale* reaches the column widths as well as the cells, which is why
    `_column_widths` takes one: it measures a column by the longest text it
    actually holds, and `1.234,50 EUR` is not the same number of characters as
    `1,234.50` in every jurisdiction. A width measured in one grammar and drawn
    in another is a table that overflows its box for no visible reason.
    """
    pptx_pkg = _require_pptx()
    plan = _plan(ir, profile)
    g = _genome_for(ir)

    presentation = pptx_pkg.Presentation()
    presentation.slide_width = SLIDE_W
    presentation.slide_height = SLIDE_H

    for slide_plan in plan.slides:
        if slide_plan.kind == "cover":
            _draw_cover(presentation, plan, g)
        elif slide_plan.kind == "divider":
            _draw_divider(presentation, slide_plan.heading, g)
        elif slide_plan.kind == "closing":
            _draw_closing(presentation, plan, g)
        else:
            _draw_content(presentation, plan, slide_plan, facts, g, locale, profile)

    properties = presentation.core_properties
    properties.title = ir.title
    properties.subject = ir.subtitle or ""
    properties.author = ir.metadata.get("author") or "Worldloom"
    properties.comments = ir.metadata.get("note", "Synthetic corpus generated by Worldloom.")
    properties.keywords = "synthetic,worldloom,seed=" + ir.metadata.get("worldloom_seed", "")
    if ir.metadata.get("voice") and profile.provenance == "properties":
        # PowerPoint's category field, for `docx.render`'s reason: the brief
        # is worth keeping and belongs off the slides.
        properties.category = (
            f"voice: {ir.metadata['voice']}; persona: {ir.metadata.get('persona', '')}"
        )

    from io import BytesIO

    buffer = BytesIO()
    presentation.save(buffer)
    # Dates come from the world, never the clock — see `ooxml.normalise`. Both
    # python-pptx's per-entry zip timestamps and its template's own static
    # `docProps/core.xml` dates are wall-clock or template artefacts, exactly
    # the defect `ooxml.py` exists to correct for DOCX and XLSX alike.
    return ooxml.normalise(buffer.getvalue(), created=ir.metadata.get("worldloom_created"))


def render_all(world: World) -> list[Rendered]:
    """Render every executive-summary-shaped artifact in *world*."""
    facts = {fact.id: fact for fact in world.facts}
    locale = corpus_locale(world)
    profile = presentation_of(world)
    out: list[Rendered] = []
    for ir in world.artifact_irs:
        intent = world.artifact_intents.by_id(ir.intent_id)
        if intent.artifact_type not in HANDLES:
            continue
        out.append(
            Rendered(
                artifact_id=ir.id,
                path=f"artifacts/{ir.id.lower()}-{slug_for(intent.artifact_type)}.pptx",
                media_type=MEDIA_TYPE,
                payload=render(ir, facts, locale=locale,
                               profile=profile.for_doctype(intent.artifact_type)),
            )
        )
    return out
