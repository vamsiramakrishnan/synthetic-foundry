@dataclass(frozen=True)
class SlidePlan:
    """One slide's resolved content, already assigned a component family.

    Renderer-local and rebuilt on every render — see the module docstring.
    ``kind`` picks the slide's furniture (a cover has no header band, a
    divider has no footer table); ``component_id`` is the compiler's choice of
    family for content slides, and it only ever selects a *visual treatment*.
    What actually appears is always ``body`` or ``table`` off the IR section
    this plan came from — never something the component id invents.
    """

    kind: str  # "cover" | "divider" | "content" | "closing"
    component_id: str
    heading: str
    body: str | None = None
    table: Table | None = None
    hidden: bool = False


@dataclass(frozen=True)
class PresentationPlan:
    """The whole deck, before a single shape exists."""

    title: str
    subtitle: str | None
    metadata: dict[str, str]
    slides: tuple[SlidePlan, ...]


#: The size class and density profile handed to the compiler. Not read off the
#: originating ``ArtifactIntent`` — ``render(ir, facts)`` carries the same
#: signature as every other format here and the IR itself does not carry a
#: size class, so threading the intent through would widen this module's
#: surface for a value that is already implied: every ``executive_summary`` in
#: `generators/planning.py` is planned as ``"small"``, because it is an
#: executive committee's one-pager, not a workbook. If a future
#: ``executive_summary`` ever grows past the four beats that implies,
#: ``compose`` raises rather than silently overflowing a slide — see `_plan`.
_SIZE_CLASS = "small"
_DENSITY_PROFILE = "balanced"


def _plan(ir: ArtifactIR) -> PresentationPlan:
    """``ArtifactIR`` -> ``PresentationPlan``, by way of the compiler.

    ``compose`` decides which component family presents each section and
    checks the resulting sequence reads as a document a company would issue
    (``docs/artifact-compiler.md`` section 4). This function's only job is to
    turn that validated sequence into slides, adding the structural slides —
    cover, appendix divider, closing — that the compiler has no opinion about
    because they carry no beat of the argument.
    """
    plan = plan_from_ir(
        ir,
        artifact_type="executive_summary",
        size_class=_SIZE_CLASS,
        density_profile=_DENSITY_PROFILE,
    )
    composition = compose(plan, fmt="pptx")
    if not composition.ok:
        raise RenderError(
            f"{ir.id}: component sequence is not a grammatical executive_summary: "
            + "; ".join(str(v) for v in composition.violations)
        )

    # `plan.beats` and `ir.sections` are built 1:1, in order, by `plan_from_ir`
    # — one beat per section, nothing filtered before `compose` runs — so
    # zipping them is the correct way back to the section a beat came from,
    # without re-deriving the beat-key slug `compose` computes internally.
    section_by_beat = {beat.key: section for beat, section in zip(plan.beats, ir.sections)}

    slides: list[SlidePlan] = [SlidePlan(kind="cover", component_id="cover", heading=ir.title)]
    appendix_opened = False
    for component_id, beat_key in zip(composition.components, composition.beats):
        section = section_by_beat[beat_key]
        if section.hidden and not appendix_opened:
            # One divider, however many hidden sections fall inside the
            # appendix — not one per section, which would read as the deck
            # repeatedly announcing the same change of subject.
            slides.append(
                SlidePlan(kind="divider", component_id="core.section_divider", heading="Appendix")
            )
            appendix_opened = True
        slides.append(
            SlidePlan(
                kind="content",
                component_id=component_id,
                heading=section.heading,
                body=section.body,
                table=section.table,
                hidden=section.hidden,
            )
        )
    slides.append(SlidePlan(kind="closing", component_id="closing", heading="Closing"))

    return PresentationPlan(title=ir.title, subtitle=ir.subtitle, metadata=ir.metadata, slides=tuple(slides))


