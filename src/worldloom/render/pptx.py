#: The same palette `docx.py` uses (its ``_HEADER_FILL`` and negative red),
#: reused rather than re-derived — a reader who has seen the memo should
#: recognise the deck as the same company's document, not a different colour
#: scheme wearing the same title.
_HEADER_FILL = "2F4858"
_ACCENT_FILL = "EDF2F4"
_NEGATIVE = "9B2226"
_INK = "1B1F22"
_MUTED = "6B747B"
_SUBTITLE_INK = "4A555C"
_WHITE = "FFFFFF"

#: No text on any slide goes below this. PowerPoint's own accessibility
#: checker starts flagging body copy under 18pt for a *projected* deck, but
#: nothing this renderer produces is meant to be read from the back of a room
#: — it is read on a screen, the same way the DOCX and Markdown twins of the
#: same artifact are. 12pt is the floor below which even screen reading starts
#: to strain, and it is deliberately not lower than the smallest text DOCX
#: itself ever uses (`docx.py`'s footnote and table text sit at 8-9pt, but
#: that is on an A4 page held close, which a slide viewed at arm's length is
#: not).
MIN_FONT_PT = 12


def _rgb(hexcode: str):  # type: ignore[no-untyped-def]
    from pptx.dml.color import RGBColor

    return RGBColor.from_string(hexcode)


def _pt(size: int):  # type: ignore[no-untyped-def]
    from pptx.util import Pt

    assert size >= MIN_FONT_PT, f"{size}pt would sit below the {MIN_FONT_PT}pt floor — see MIN_FONT_PT"
    return Pt(size)


def _textbox(slide, box: Box, *, fill: str | None = None):  # type: ignore[no-untyped-def]
    """A text box at *box*, transparent unless *fill* is given.

    Every text-bearing shape in this module goes through here, which is what
    keeps word-wrap, margins, and the no-autofit choice below uniform instead
    of each ``_draw_*`` function reimplementing them slightly differently.
    """
    from pptx.enum.text import MSO_AUTO_SIZE

    _assert_in_bounds(box)
    shape = slide.shapes.add_textbox(box.x, box.y, box.cx, box.cy)
    frame = shape.text_frame
    frame.word_wrap = True
    # Not the default. `SHAPE_TO_FIT_TEXT` is a hint for the *next* editor to
    # resize the shape around its text — left on, a box we sized deliberately
    # could grow past the bounds this module computed the moment someone
    # opens and re-saves the deck. This renderer owns the geometry; nothing
    # downstream should get to override it.
    frame.auto_size = MSO_AUTO_SIZE.NONE
    frame.margin_left = frame.margin_right = _in(0.12)
    frame.margin_top = frame.margin_bottom = _in(0.06)
    if fill is not None:
        shape.fill.solid()
        shape.fill.fore_color.rgb = _rgb(fill)
        shape.line.fill.background()
    else:
        shape.fill.background()
        shape.line.fill.background()
    return shape


def _write(
    frame,  # type: ignore[no-untyped-def]
    paragraphs: list[str],
    *,
    size: int,
    colour: str,
    bold: bool = False,
    italic: bool = False,
    align=None,  # type: ignore[no-untyped-def]
) -> None:
    """Fill a text frame with one paragraph per string, uniformly styled.

    Every run gets an explicit size and colour rather than inheriting the
    theme default — inheritance is exactly what would let a run slip under
    ``MIN_FONT_PT`` unnoticed, since nothing would ever assign it a size to
    check.
    """
    first = True
    for text in paragraphs:
        if not text:
            continue
        paragraph = frame.paragraphs[0] if first else frame.add_paragraph()
        first = False
        paragraph.text = text
        if align is not None:
            paragraph.alignment = align
        run = paragraph.runs[0]
        run.font.size = _pt(size)
        run.font.bold = bold
        run.font.italic = italic
        run.font.color.rgb = _rgb(colour)


def _new_slide(prs, heading: str, *, footer_text: str):  # type: ignore[no-untyped-def]
    """A blank slide with the two bands every content slide shares."""
    from pptx.enum.text import MSO_ANCHOR, PP_ALIGN

    slide = prs.slides.add_slide(prs.slide_layouts[6])  # "Blank" — see module docstring

    header = _textbox(slide, HEADER, fill=_HEADER_FILL)
    header.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    _write(header.text_frame, [heading], size=24, colour=_WHITE, bold=True)

    footer = _textbox(slide, FOOTER)
    footer.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    _write(footer.text_frame, [footer_text], size=MIN_FONT_PT, colour=_MUTED, italic=True, align=PP_ALIGN.CENTER)

    return slide


