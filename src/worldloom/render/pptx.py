_EMU_PER_INCH = 914_400


def _in(inches: float) -> int:
    """Inches to EMU, the unit every OOXML coordinate is stored in.

    A plain function rather than reaching for ``pptx.util.Inches`` — the
    geometry constants below are computed at import time, before
    ``_require_pptx`` has run, so they cannot depend on the optional package.
    ``Emu``/``Inches`` are themselves just ``int`` subclasses; python-pptx
    accepts a bare EMU int anywhere it accepts a ``Length``.
    """
    return round(inches * _EMU_PER_INCH)


#: Widescreen, because every deck this renders is a 2020s corporate one, not a
#: 2003-era projector. 13.333 x 7.5in is PowerPoint's own 16:9 default size.
SLIDE_W = _in(13.333)
SLIDE_H = _in(7.5)

#: Outer margin and the gap between stacked regions. Not copied from `docx.py`
#: verbatim — its 22mm page margin (~0.87in) is tuned for an A4 page held
#: close; a slide is wider and shorter, and the same margin there would eat a
#: third of the usable width. Tighter, so the two formats read as
#: proportionate rather than as one renderer ignoring the other's convention.
_MARGIN = _in(0.55)
_GUTTER = _in(0.25)

#: The coloured band carrying a slide's heading, and the footer strip below the
#: body. Both span the full slide width (no side margin) — a full-bleed band
#: is what makes a slide read as "a deck" rather than "a page with a border".
_HEADER_H = _in(0.85)
_FOOTER_H = _in(0.35)

_CONTENT_X = _MARGIN
_CONTENT_W = SLIDE_W - 2 * _MARGIN

_BODY_Y = _HEADER_H + _GUTTER
_FOOTER_Y = SLIDE_H - _FOOTER_H
_BODY_H = _FOOTER_Y - _GUTTER - _BODY_Y


@dataclass(frozen=True)
class Box:
    """One rectangle in EMU. The only geometry primitive this renderer has.

    Nothing below ever searches for a box — every ``Box`` is either a module
    constant or arithmetic over one (see ``_stack`` and ``_columns``), which is
    what "deterministic greedy layout" concretely means here: the same IR
    produces the same boxes because there is no search, only addition.
    """

    x: int
    y: int
    cx: int
    cy: int

    @property
    def right(self) -> int:
        return self.x + self.cx

    @property
    def bottom(self) -> int:
        return self.y + self.cy


#: The three horizontal bands every slide is built from, fixed for the whole
#: deck. A slide-specific layout only ever subdivides ``BODY``; ``HEADER`` and
#: ``FOOTER`` are the same rectangle on every slide, which is what stops a
#: one-off slide from silently drifting the deck's furniture out from under
#: the rest.
HEADER = Box(0, 0, SLIDE_W, _HEADER_H)
BODY = Box(_CONTENT_X, _BODY_Y, _CONTENT_W, _BODY_H)
FOOTER = Box(0, _FOOTER_Y, SLIDE_W, _FOOTER_H)


def _assert_in_bounds(box: Box) -> None:
    """A shape that starts life out of bounds is a bug in this renderer's own
    arithmetic, not something the structural validator downstream should have
    to be the first to catch."""
    assert box.x >= 0 and box.y >= 0, box
    assert box.right <= SLIDE_W and box.bottom <= SLIDE_H, box


def _stack(x: int, top: int, width: int, heights: list[int], gap: int = _GUTTER) -> list[Box]:
    """*heights* laid out downward from *top*, each separated by *gap*.

    The one layout combinator this renderer needs: every multi-element slide
    (the cover, a prose slide with an accent bar) is boxes stacked or set side
    by side, never positioned by hand — which is what makes non-overlap a
    property of the arithmetic rather than something checked after the fact,
    box by box.
    """
    boxes = []
    y = top
    for h in heights:
        boxes.append(Box(x, y, width, h))
        y += h + gap
    return boxes


def _columns(box: Box, count: int, gap: int = _GUTTER) -> list[Box]:
    """*box* split into *count* equal-width columns side by side."""
    width = (box.cx - gap * (count - 1)) // count
    return [Box(box.x + i * (width + gap), box.y, width, box.cy) for i in range(count)]


