@dataclass(frozen=True)
class DocumentPlan:
    """Renderer-local: fixed page geometry, plus the section order and any drops
    the artifact compiler decided.

    Per ``docs/artifact-compiler.md`` §2, a plan may decide which page a section
    lands on and whether detail moves to an appendix; it may not decide which
    facts are true or which rows belong in a table — those are already fixed by
    the time an ``ArtifactIR`` exists. Never persisted: rebuilt from the IR on
    every render, so it cannot drift from the artifact it describes.
    """

    page_width_pt: float
    page_height_pt: float
    margin_pt: float
    sections: tuple[ArtifactSection, ...]
    """``ir.sections``, reordered exactly as the compiler's composition ordered
    the beats built from them — identity order today, since nothing in the
    shipped vocabulary requires a repair (`compose._repair_order`), but this is
    what makes a future reorder or drop take effect here without a second
    decision being made in this module."""
    dropped: tuple[str, ...]
    """Section headings the compiler dropped as over-budget optional material.
    Always empty against the artifacts this repository ships — see the report
    for why — but respected rather than assumed away."""
    violations: tuple[GrammarViolation, ...]
    """Grammar violations in the composed sequence, carried through rather than
    silenced. Empty for every shipped artifact type; a non-empty tuple here is
    a defect upstream of this renderer, not something this module can repair,
    so it does not raise — the caller (a future validator) can inspect it."""
    components: dict[str, str]
    """Section heading -> the component id the compiler chose for it.

    What lets `_section_flowables` dispatch on component *identity* — a
    section composed as `editorial.pull_quote` draws a quotation, one composed
    as `ops.causal_chain` with a declared flow draws a chain — beyond the
    shape-based body/table/awaiting fallback every section already got. Built
    from the same `composition` this plan's ordering already comes from, so
    there is no second call to the compiler and no way for the two to disagree.
    """


def _plan(ir: ArtifactIR, artifact_type: str, size_class: SizeClass) -> DocumentPlan:
    """Derive a page plan from *ir* via the artifact compiler.

    Composed against ``pdf`` in its own right. This originally borrowed
    ``docx``, because no component declared ``pdf`` at all — a reasonable
    stopgap that was also a quiet lie: it would have kept working, and kept
    reporting success, long after the two formats diverged. Every component
    spellable in Word is spellable in a fixed-page projection of the same IR,
    so the registry now says so, and this asks for what it actually renders.
    """
    plan = plan_from_ir(ir, artifact_type=artifact_type, size_class=size_class)
    try:
        composition = compose(plan, fmt="pdf")
    except ValueError as exc:
        raise RenderError(f"{ir.id}: cannot compose a page plan: {exc}") from exc

    # `plan.beats` is built one beat per `ir.section`, in that same order (see
    # `plan_from_ir`), so this zip is a true parallel pairing rather than a
    # guess — the only thing `composition.beats` can have done to that order is
    # drop entries or move one earlier via `_repair_order`.
    section_by_beat = dict(zip((beat.key for beat in plan.beats), ir.sections))
    ordered = tuple(section_by_beat[key] for key in composition.beats)
    components = {
        section_by_beat[key].heading: component_id
        for key, component_id in zip(composition.beats, composition.components)
    }

    return DocumentPlan(
        page_width_pt=_PAGE_WIDTH_PT,
        page_height_pt=_PAGE_HEIGHT_PT,
        margin_pt=_MARGIN_PT,
        sections=ordered,
        dropped=composition.dropped,
        violations=composition.violations,
        components=components,
    )


