def _table_flowable(table: Table, frame_width: float, styles: dict):  # type: ignore[no-untyped-def]
    """One IR table as a paginating platypus table.

    ``repeatRows=1`` is what gives this renderer real pagination for free: when
    platypus splits a table across a page boundary it repeats row 0 — our
    header — on the continuation, which is the "header repeated" half of the
    task's pagination rule stated as a table property rather than code this
    module has to write. The other half — a single row too tall for an empty
    page — is not a per-table decision; see `render` for how that is handled
    when it happens.

    Numbers are right-aligned and subtotal rows shaded, matching
    `render/docx.py::_table` cell for cell, because both read the same
    `format_value` and a reader should not be able to tell which renderer
    produced a given figure.
    """
    from reportlab.lib import colors
    from reportlab.platypus import Paragraph
    from reportlab.platypus import Table as PlatypusTable
    from reportlab.platypus import TableStyle

    label_width = frame_width * 0.34
    per_column = (frame_width - label_width) / max(1, len(table.columns))
    col_widths = [label_width] + [per_column] * len(table.columns)

    header_row = [Paragraph(_escape(table.title), styles["cell_header"])]
    header_row += [Paragraph(_escape(column.label), styles["cell_right_header"]) for column in table.columns]
    data = [header_row]

    commands = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(f"#{_HEADER_FILL}")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#C7CDD1")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]

    for row_index, row in enumerate(table.rows, start=1):
        cells = [Paragraph(_escape(row.label), styles["cell_bold" if row.emphasis else "cell"])]
        for column in table.columns:
            cell = row.cells.get(column.key)
            value = cell.value if cell else None
            text = format_value(value, column.number_format) if cell else ""
            negative = isinstance(value, (int, float)) and value < 0
            # A negative is already parenthesised by `format_value`; colour is
            # the second signal, never the only one, so the table survives
            # being printed in black and white — same rule `docx._table` uses.
            key = (
                "cell_right_negative_bold" if negative and row.emphasis
                else "cell_right_negative" if negative
                else "cell_right_bold" if row.emphasis
                else "cell_right"
            )
            cells.append(Paragraph(_escape(text), styles[key]))
        data.append(cells)
        if row.emphasis:
            commands.append(("BACKGROUND", (0, row_index), (-1, row_index), colors.HexColor(f"#{_SUBTOTAL_FILL}")))

    grid = PlatypusTable(data, colWidths=col_widths, repeatRows=1)
    grid.setStyle(TableStyle(commands))
    return grid


def _figure_flowables(chart, table: Table, frame_width: float, styles: dict) -> list:  # type: ignore[no-untyped-def]
    """A declared chart, drawn as proportional bars from the same cells the
    table above shows — never a second computation of the data.

    `render/docx.py::_figure` draws its bars from block glyphs (``█``) because
    python-docx has no drawing API to reach for. reportlab's canvas does, and a
    block glyph turned out to be the wrong choice to port: it sits outside the
    WinAnsi encoding the base-14 fonts use, so Helvetica silently substitutes an
    unrelated character for it — confirmed while building this renderer by
    inspecting the emitted content stream. A rectangle scaled by simple
    arithmetic (see `_Bar` below) is exactly as deterministic as a glyph count
    and does not depend on what a font happens to map a codepoint to.
    """
    from reportlab.lib import colors
    from reportlab.platypus import Flowable, Paragraph
    from reportlab.platypus import Table as PlatypusTable
    from reportlab.platypus import TableStyle

    class _Bar(Flowable):
        """A single proportional bar, vector-drawn to a fixed height."""

        def __init__(self, fraction: float, width: float, height: float, colour) -> None:  # type: ignore[no-untyped-def]
            super().__init__()
            self.fraction = fraction
            self.width = width
            self.height = height
            self.colour = colour

        def wrap(self, avail_width: float, avail_height: float) -> tuple[float, float]:
            return self.width, self.height

        def draw(self) -> None:
            self.canv.setFillColor(self.colour)
            self.canv.rect(0, 0, self.width * self.fraction, self.height, stroke=0, fill=1)

    if not chart.series:
        return []
    measure = chart.series[0]
    column = table.column(measure)
    rows = [row for row in table.rows if row.key in set(chart.rows)] or list(table.rows)

    values: list[tuple[str, float]] = []
    for row in rows:
        cell = row.cells.get(measure)
        if cell is not None and isinstance(cell.value, (int, float)):
            values.append((row.label, float(cell.value)))
    if not values:
        return []

    widest = max(abs(value) for _, value in values) or 1.0
    label_width = frame_width * 0.30
    value_width = frame_width * 0.20
    bar_width = frame_width - label_width - value_width

    data = []
    commands = [
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 2),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]
    for name, value in values:
        colour = colors.HexColor(f"#{_NEGATIVE if value < 0 else _HEADER_FILL}")
        fraction = min(1.0, abs(value) / widest)
        formatted = format_value(value, column.number_format if column else None)
        data.append([
            Paragraph(_escape(name), styles["cell"]),
            Paragraph(_escape(formatted), styles["cell_right"]),
            _Bar(fraction, bar_width, 8, colour),
        ])

    grid = PlatypusTable(data, colWidths=[label_width, value_width, bar_width])
    grid.setStyle(TableStyle(commands))

    flow = [Paragraph(f"Figure — {_escape(chart.title)}", styles["figure_title"]), grid]
    if chart.note:
        flow.append(Paragraph(_escape(chart.note), styles["figure_note"]))
    return flow


def _section_flowables(
    section: ArtifactSection, facts: dict[str, CanonicalFact] | None, styles: dict, frame_width: float
) -> list:
    """One IR section as a run of flowables: heading, then body or table."""
    from reportlab.platypus import Paragraph, Spacer

    flow: list = [Paragraph(_escape(section.heading), styles["heading"])]
    if section.hidden:
        flow.append(Paragraph(_escape(_HIDDEN_NOTE), styles["hidden"]))

    # `purpose` is shown only when there is no prose to carry it — a finished
    # paragraph already says what the section is for; a table or an
    # awaiting-narrative placeholder does not, and that is where a reader
    # benefits from the one-line brief the outline wrote for the narrator.
    if section.purpose and section.body is None:
        flow.append(Paragraph(_escape(section.purpose), styles["purpose"]))

    if section.body:
        text = references.substitute(section.body, facts) if facts else section.body
        for block in (part.strip() for part in text.split("\n\n")):
            if block:
                flow.append(Paragraph(_escape(block), styles["body"]))
    elif section.table is not None:
        flow.append(_table_flowable(section.table, frame_width, styles))
        if section.table.note:
            flow.append(Paragraph(_escape(section.table.note), styles["note"]))
    else:
        flow.append(Paragraph(_escape(_AWAITING), styles["awaiting"]))

    # After the chain, never inside it. `render/docx.py` and `render/markdown.py`
    # both carry the same note: a `for` placed between the `elif` and the `else`
    # above binds the `else` to the loop rather than to the conditional, and
    # Python runs a loop-else whenever the loop did not break — which is how
    # that defect first shipped, in the Markdown renderer.
    for chart in section.charts:
        if section.table is not None:
            flow.extend(_figure_flowables(chart, section.table, frame_width, styles))

    flow.append(Spacer(1, 4))
    return flow


