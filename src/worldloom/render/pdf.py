# Determinism: the PDF-specific clock and identity hazards
# ---------------------------------------------------------------------------

_CREATION_DATE = re.compile(rb"(/CreationDate\s*\()[^)]*(\))")
_MOD_DATE = re.compile(rb"(/ModDate\s*\()[^)]*(\))")


def _pdf_date(instant: tuple[int, int, int, int, int, int]) -> str:
    """*instant* as a PDF date string, ``D:YYYYMMDDHHmmSS+00'00'``."""
    year, month, day, hour, minute, second = instant
    return f"D:{year:04d}{month:02d}{day:02d}{hour:02d}{minute:02d}{second:02d}+00'00'"


def _normalise(payload: bytes) -> bytes:
    """Rewrite ``/CreationDate`` and ``/ModDate`` to the epoch every Office
    package in this repository already uses.

    reportlab's own ``invariant=True`` (passed when the document is built)
    already does most of the work: it swaps ``time.time()`` for a fixed instant
    project-wide, which is what keeps `/ID` — a hash of document content salted
    with that instant — a function of content alone rather than of content and
    wall-clock time. But the instant reportlab substitutes is *its* choice
    (2000-01-01), not this project's. `render/ooxml.py` fixes the equivalent
    hazard in DOCX and XLSX to ``EPOCH = (1980, 1, 1, 0, 0, 0)``; this rewrites
    the same two Info-dictionary fields to that instant so a PDF and a DOCX of
    the same corpus agree about when the corpus was made, rather than each
    being internally constant but disagreeing with the other.

    A narrow byte substitution, like `ooxml.normalise` — the value is a literal
    PDF string with no nested parentheses, so this does not need a PDF parser.
    """
    stamp = _pdf_date(ooxml.EPOCH).encode()
    payload = _CREATION_DATE.sub(rb"\g<1>" + stamp + rb"\g<2>", payload, count=1)
    payload = _MOD_DATE.sub(rb"\g<1>" + stamp + rb"\g<2>", payload, count=1)
    return payload


