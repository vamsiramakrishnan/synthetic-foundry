def _header_drawer(text: str):  # type: ignore[no-untyped-def]
    """An ``onPage`` callback that writes the running header — the company and
    the document title, right-aligned in the top margin, same content as
    `render/docx.py::_running_heads`. Needs no total page count, unlike the
    footer, so it draws directly rather than through the buffering trick below.
    """

    def draw(canvas, doc) -> None:  # type: ignore[no-untyped-def]
        from reportlab.lib.colors import HexColor

        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(HexColor(f"#{_MUTED}"))
        canvas.drawRightString(_PAGE_WIDTH_PT - _MARGIN_PT, _PAGE_HEIGHT_PT - _MARGIN_PT + 8, text)
        canvas.restoreState()

    return draw


def _numbered_canvas_class(footer_note: str):  # type: ignore[no-untyped-def]
    """Build a `Canvas` subclass that captions every page ``Page X of Y``.

    The footer needs the total page count, and `Canvas.save()` writes pages as
    they are produced — the total is not known until the whole story has been
    laid out. This is the standard reportlab technique for that: buffer each
    page's finished drawing state instead of emitting it immediately, and once
    `save()` is called (so the total is known) replay every buffered page,
    drawing the footer on each before it is actually written. Nothing here
    reads the clock or a random source — it replays state this render already
    computed, plus one integer — so it is exactly as deterministic as every
    other page in the document.

    A class factory rather than a module-level class: the class subclasses
    `reportlab.pdfgen.canvas.Canvas`, and every reportlab name in this module is
    imported inside a function so an optional dependency for one format cannot
    break import of the package as a whole.
    """
    from reportlab.lib import colors
    from reportlab.pdfgen import canvas as canvas_module

    class _NumberedCanvas(canvas_module.Canvas):
        def __init__(self, *args, **kwargs) -> None:  # type: ignore[no-untyped-def]
            super().__init__(*args, **kwargs)
            self._worldloom_pages: list[dict] = []

        def showPage(self) -> None:
            self._worldloom_pages.append(dict(self.__dict__))
            self._startPage()

        def save(self) -> None:
            total = len(self._worldloom_pages)
            for state in self._worldloom_pages:
                self.__dict__.update(state)
                self._draw_footer(total)
                canvas_module.Canvas.showPage(self)
            canvas_module.Canvas.save(self)

        def _draw_footer(self, total: int) -> None:
            self.saveState()
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor(f"#{_MUTED}"))
            self.drawCentredString(
                _PAGE_WIDTH_PT / 2,
                _MARGIN_PT - 10,
                f"{footer_note}    Page {self._pageNumber} of {total}",
            )
            self.restoreState()

    return _NumberedCanvas


