"""The native PDF renderer.

``docs/artifact-compiler.md`` §9.4 treats PDF as "derived by default" — DOCX and
PPTX converted through LibreOffice — and reserves a native renderer for an
artifact whose *canonical* form is PDF. This module exists anyway, because the
derived path cannot satisfy the property every other format in this package is
held to: CI regenerates a corpus from its ledger and diffs it byte-for-byte, and
a LibreOffice conversion is not byte-reproducible across machines or LibreOffice
versions — it is an external, version-dependent binary, not a projection of the
IR. A derived PDF can be a *preview* for the visual harness (§11.D scopes it
exactly that way, "behind capability detection"); it can never be a ``-f pdf``
corpus artifact. So ``-f pdf`` is a second, deterministic, pure-Python projection
of the same ``ArtifactIR`` the DOCX renderer reads — built with ``reportlab``,
which never shells out — rather than a conversion of the DOCX renderer's own
output.

Same rule as every other renderer: this reads the IR and nothing else. Every
figure it draws is a cell ``format_value`` already agreed on with Markdown and
DOCX; nothing here computes one. See ``tests/test_pdf.py`` for the proof that
two renders of the same IR, even in separate processes, are byte-identical —
the property a derived PDF could never offer.

What becomes of a hidden section is ``presentation.py``'s decision, not this
renderer's — and it is still true that an appendix present in one format and
silently absent from another would be two documents of one artifact
disagreeing. That invariant now holds because every format asks the *same*
corpus-wide profile, rather than because every format was hardcoded the same
way. ``table_fit`` is this renderer's alone, because only a fixed-page format
has a column-width problem at all.
"""

