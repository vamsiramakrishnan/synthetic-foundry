def render(
    ir: ArtifactIR,
    facts: dict[str, CanonicalFact] | None = None,
    *,
    artifact_type: str = "",
    size_class: SizeClass = "medium",
) -> bytes:
    """Render one IR to PDF bytes.

    Prose carries ``{{fact:ID}}`` references; *facts* resolves them at render
    time. Without it the references stay visible, which is the right failure —
    a document that quietly drops a figure reads as complete and is not.

    *artifact_type* and *size_class* feed the artifact compiler's page plan
    (see ``_plan``); both default to values that compose against every
    artifact type this renderer ships against, so a bare ``render(ir, facts)``
    — the shape `tests/test_docx.py`'s idiom uses — still works for a
    determinism check that does not care about composition.
    """
    _require_reportlab()
    from reportlab.platypus import BaseDocTemplate, Frame, PageTemplate, Paragraph
    from reportlab.platypus.doctemplate import LayoutError

    plan = _plan(ir, artifact_type, size_class)
    styles = _styles()
    frame_width = plan.page_width_pt - 2 * plan.margin_pt

    story: list = [Paragraph(_escape(ir.title), styles["title"])]
    if ir.subtitle:
        story.append(Paragraph(_escape(ir.subtitle), styles["subtitle"]))

    author = ir.metadata.get("author")
    if author:
        byline = author
        if ir.metadata.get("author_title"):
            byline += f", {ir.metadata['author_title']}"
        story.append(Paragraph(_escape(byline), styles["byline"]))

    story.append(Paragraph(
        _escape(ir.metadata.get("note", "Synthetic corpus generated by Worldloom. Not a real company.")),
        styles["notice"],
    ))

    for section in plan.sections:
        story.extend(_section_flowables(section, facts, styles, frame_width))

    if ir.metadata.get("voice"):
        story.append(Paragraph(
            _escape(f"Author voice: {ir.metadata['voice']}. Persona: {ir.metadata.get('persona', '')}."),
            styles["note"],
        ))

    buffer = BytesIO()
    doc = BaseDocTemplate(
        buffer,
        pagesize=(plan.page_width_pt, plan.page_height_pt),
        leftMargin=plan.margin_pt,
        rightMargin=plan.margin_pt,
        topMargin=plan.margin_pt,
        bottomMargin=plan.margin_pt,
        title=ir.title,
        author=ir.metadata.get("author") or "Worldloom",
        subject=ir.subtitle or "",
        creator="Worldloom",
        keywords=["synthetic", "worldloom", f"seed={ir.metadata.get('worldloom_seed', '')}"],
        # `invariant` is reportlab's own documented determinism switch — it
        # substitutes a fixed instant for `time.time()` everywhere the library
        # would otherwise reach for the clock, including the digest that seeds
        # `/ID`. `pageCompression=0` keeps every content stream as literal
        # bytes rather than deflated ones, which is what lets a figure be
        # verified by searching the file the same way a fact is checked
        # against the Markdown twin (see `tests/test_pdf.py`) — a diffable
        # native artifact, the same virtue `render/markdown.py` was written
        # for, at the cost of a larger file than a shipped PDF viewer would
        # produce.
        invariant=True,
        pageCompression=0,
    )
    frame = Frame(plan.margin_pt, plan.margin_pt, frame_width, plan.page_height_pt - 2 * plan.margin_pt, id="body")
    header_text = " · ".join(part for part in (ir.metadata.get("company"), ir.title) if part)
    footer_note = ir.metadata.get("note", "Synthetic corpus generated by Worldloom.")
    doc.addPageTemplates([PageTemplate(id="main", frames=[frame], onPage=_header_drawer(header_text))])

    try:
        doc.build(story, canvasmaker=_numbered_canvas_class(footer_note))
    except LayoutError as exc:
        # A single row taller than an empty page cannot be split further —
        # `Table.split()` has nothing left to try, and platypus raises rather
        # than silently clipping content. Turned into a `RenderError` naming
        # the artifact rather than left as reportlab's own exception, so a
        # caller sees which document failed and why instead of a bare layout
        # message with no artifact id in it.
        raise RenderError(
            f"{ir.id}: a table row does not fit on a single page even alone — "
            f"shorten its content or widen the page margins ({exc})"
        ) from exc

    return _normalise(buffer.getvalue())


def render_all(world: World) -> list[Rendered]:
    """Render every document-shaped artifact in *world* — the same set
    `render/docx.py` handles, since a native-PDF artifact and a Word artifact
    are the same document-shaped content, just spelled in two fixed-page
    formats. Reused from there rather than duplicated, so the two lists cannot
    quietly drift apart.
    """
    facts = {fact.id: fact for fact in world.facts}
    out: list[Rendered] = []
    for ir in world.artifact_irs:
        intent = world.artifact_intents.by_id(ir.intent_id)
        if intent.artifact_type not in HANDLES:
            continue
        out.append(
            Rendered(
                artifact_id=ir.id,
                path=f"artifacts/{ir.id.lower()}-{slug_for(intent.artifact_type)}.pdf",
                media_type=MEDIA_TYPE,
                payload=render(
                    ir, facts, artifact_type=intent.artifact_type, size_class=intent.size_profile
                ),
            )
        )
    return out
